/**
 * Generates `src/shared/geo/ukBoundary.ts` from Geofabrik's region index.
 *
 * The UK default speed limits (ADR 0018) apply only inside the United Kingdom,
 * so the app needs a boundary it can test offline. Geofabrik's `united-kingdom`
 * feature is exactly that: 150 points, with Northern Ireland inside and the
 * Republic of Ireland, the Isle of Man and the Channel Islands outside, which
 * is the distinction the law draws.
 *
 * Generated rather than hand-written so that the coordinates are provably the
 * published ones, and can be refreshed by re-running this.
 *
 *   node scripts/generate-uk-boundary.mjs [path/to/index-v1.json]
 *
 * With no argument it reads the copy the app caches in its user-data
 * directory, which exists once the region picker has been opened.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const source =
  process.argv[2] ??
  path.join(homedir(), 'Library/Application Support/trailrt/valhalla/geofabrik-index.json');

const index = JSON.parse(readFileSync(source, 'utf8'));
const feature = index.features.find((f) => f.properties?.id === 'united-kingdom');
if (feature === undefined) throw new Error('no united-kingdom feature in the index');

const { type, coordinates } = feature.geometry;
const polygons = type === 'MultiPolygon' ? coordinates : [coordinates];
if (polygons.length !== 1) throw new Error(`expected one polygon, found ${polygons.length}`);
const ring = polygons[0][0];

const body = ring
  .map(([lon, lat]) => `  [${lon.toFixed(5)}, ${lat.toFixed(5)}],`)
  .join('\n');

const out = `import type { LatLon } from './distance';
import { pointInRing, ringsBoundingBox, type Ring } from './polygon';

/**
 * The United Kingdom's boundary, for deciding where UK speed-limit law applies.
 *
 * GENERATED by \`scripts/generate-uk-boundary.mjs\` from the \`united-kingdom\`
 * feature of Geofabrik's region index. Do not edit by hand; re-run the script.
 *
 * Derived from OpenStreetMap data: © OpenStreetMap contributors, ODbL.
 *
 * Coarse on purpose — ${ring.length} points, buffered out to sea like every
 * Geofabrik boundary. On land it follows the border with the Republic of
 * Ireland closely enough for a speed-limit default: a road within a kilometre
 * or so of the border may be placed on the wrong side, and an assumed limit
 * there is labelled as assumed anyway.
 */
export const UK_BOUNDARY: Ring = [
${body}
];

const BOX = ringsBoundingBox([UK_BOUNDARY]);

/** True when a point lies inside the United Kingdom. */
export function inUk(point: LatLon): boolean {
  if (BOX === null) return false;
  if (
    point.lat < BOX.minLat ||
    point.lat > BOX.maxLat ||
    point.lon < BOX.minLon ||
    point.lon > BOX.maxLon
  ) {
    return false;
  }
  return pointInRing(UK_BOUNDARY, point);
}
`;

const target = path.join(ROOT, 'src/shared/geo/ukBoundary.ts');
writeFileSync(target, out, 'utf8');
console.log(`wrote ${target} (${ring.length} points)`);
